import { chromium } from "@playwright/test";
const base = process.env.BASE_URL ?? "http://localhost:3100";
const b = await chromium.launch();
const ctx = await b.newContext({ baseURL: base, viewport: { width: 1440, height: 900 }, colorScheme: "light" });
await ctx.request.post("/api/test/sign-in", { data: { key: "readme", name: "Mara Okafor" } });
const page = await ctx.newPage();
await page.goto("/", { waitUntil: "networkidle" });
await page.waitForTimeout(1200);
await page.screenshot({ path: "docs/hero.png" });
const ids = ((await (await ctx.request.get("/api/wander")).json()).items as Array<{ id: string }>).map((i) => i.id);
await page.goto(`/art/${ids[7]}`, { waitUntil: "networkidle" });
await page.waitForTimeout(800);
await page.screenshot({ path: "docs/detail.png" });
const w = await (await ctx.request.post("/api/walls", { data: { title: "Quiet rooms", description: "Late light, mostly.", isPublic: true, theme: "night" } })).json();
for (const id of ids.slice(0, 6)) await ctx.request.post(`/api/walls/${w.id}/items`, { data: { artworkId: id } });
await page.goto(`/walls/${w.slug}`, { waitUntil: "networkidle" });
await page.waitForTimeout(900);
await page.screenshot({ path: "docs/wall.png" });
await ctx.request.delete(`/api/walls/${w.id}`);
await b.close();
